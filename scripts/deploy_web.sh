#!/usr/bin/env bash

# Publish frontend/ on Amplify Hosting (public HTTPS URL).
# Run it after ./scripts/deploy.sh web-api, with your AWS credentials loaded.
#
# 1. Reads the web-api outputs (API URL, Cognito, Amplify app)
# 2. Builds a folder with the web files + a config.js pointing to this account
# 3. Uploads it as a manual Amplify deployment and waits until it is live

set -euo pipefail

REGION="${AWS_DEFAULT_REGION:-us-east-1}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"

ACCOUNT_ID="$(aws sts get-caller-identity --query Account --output text)" \
  || { echo "Load your AWS credentials first"; exit 1; }
STATE_BUCKET="smartfuel-tfstate-${ACCOUNT_ID}"

echo "Account ${ACCOUNT_ID} · region ${REGION}"

cd "${ROOT}/infra/web-api"
terraform init -input=false -reconfigure \
  -backend-config="bucket=${STATE_BUCKET}" \
  -backend-config="key=web-api/terraform.tfstate" \
  -backend-config="region=${REGION}" \
  -backend-config="use_lockfile=true" > /dev/null

API_URL="$(terraform output -raw api_url)"
COGNITO_DOMAIN="$(terraform output -raw cognito_domain)"
COGNITO_CLIENT_ID="$(terraform output -raw cognito_client_id)"
APP_ID="$(terraform output -raw amplify_app_id)"
WEB_URL="$(terraform output -raw web_url)"

BUILD="$(mktemp -d)"
trap 'rm -rf "${BUILD}"' EXIT

cp "${ROOT}"/frontend/{index.html,styles.css,app.js,auth.js,geohash.js} "${BUILD}/"
cat > "${BUILD}/config.js" <<EOF
// Generated by scripts/deploy_web.sh for account ${ACCOUNT_ID}
window.SMARTFUEL_CONFIG = {
  API_URL: "${API_URL}",
  COGNITO_DOMAIN: "${COGNITO_DOMAIN}",
  COGNITO_CLIENT_ID: "${COGNITO_CLIENT_ID}",
};
EOF

(cd "${BUILD}" && zip -qr site.zip index.html styles.css app.js auth.js geohash.js config.js)

echo "Uploading the web app to Amplify..."
read -r JOB_ID UPLOAD_URL < <(aws amplify create-deployment \
  --app-id "${APP_ID}" --branch-name main \
  --query '[jobId, zipUploadUrl]' --output text)

curl -sSf -X PUT -H "Content-Type: application/zip" \
  --data-binary "@${BUILD}/site.zip" "${UPLOAD_URL}" > /dev/null

aws amplify start-deployment --app-id "${APP_ID}" --branch-name main --job-id "${JOB_ID}" > /dev/null

for _ in $(seq 1 60); do
  STATUS="$(aws amplify get-job --app-id "${APP_ID}" --branch-name main --job-id "${JOB_ID}" \
    --query 'job.summary.status' --output text)"
  case "${STATUS}" in
    SUCCEED) echo; echo "Done: ${WEB_URL}"; exit 0 ;;
    FAILED|CANCELLED) echo; echo "Amplify deployment ${STATUS} (job ${JOB_ID})"; exit 1 ;;
  esac
  printf "."
  sleep 5
done

echo
echo "Still deploying after 5 minutes: check the Amplify console (job ${JOB_ID})"
exit 1
